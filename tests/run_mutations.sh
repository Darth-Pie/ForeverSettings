#!/usr/bin/env bash
# Runs every mutation against its suite and prints one of three outcomes per mutant:
#   KILLED    exit 1 and every expected test failed by name
#   SURVIVED  exit 0 (no test noticed)
#   ERROR     exit 2 (the run could not be read: pattern not found, syntax error, Lua error)
# The unmutated suites must be clean first. Controls at the end must land exactly where they should.
# Usage: bash run_mutations.sh   (from anywhere; FSET_PKG and FSET_SRC override where fengari and the addon are)
set -u
T=$(cd "$(dirname "$0")" && pwd)
# In the repository the addon is the folder above this one and fengari is installed beside the tests (npm install);
# on the author's machine they live elsewhere.
if [ -f "$T/../ForeverSettings.toc" ]; then DEFAULT_SRC=$T/..; else DEFAULT_SRC=/c/tmp/fset/build/ForeverSettings; fi
if [ -d "$T/node_modules/fengari" ]; then DEFAULT_PKG=$T; else DEFAULT_PKG=/c/tmp/fset/pkg; fi
PKG=${FSET_PKG:-$DEFAULT_PKG}
SRC=${FSET_SRC:-$DEFAULT_SRC}

for s in test_addon test_bench test_ui test_profiles test_guide test_recommend test_results test_crowd test_names test_settings test_graph; do
  if ! node "$T/run.js" "$PKG" "$SRC" "$T/$s.lua" >/dev/null 2>&1; then
    echo "BASELINE FAIL: $s is not clean, no mutation result can be trusted"
    exit 1
  fi
done
echo "baseline: test_addon, test_bench and test_ui clean"

