while IFS='|' read -r name suite ids want; do
  total=$((total + 1))
  out=$(node "$T/run.js" "$PKG" "$SRC" "$T/$suite.lua" "$name" 2>&1)
  code=$?
  failing=$(echo "$out" | grep -c '^FAIL')
